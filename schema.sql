-- Vaultbit database. The server only ever stores encrypted data.
CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS challenges (
  id TEXT PRIMARY KEY, code_hash TEXT NOT NULL, purpose TEXT NOT NULL,
  expires INTEGER NOT NULL, attempts INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY, created INTEGER NOT NULL, expires INTEGER NOT NULL, device TEXT
);
CREATE TABLE IF NOT EXISTS items (
  id TEXT PRIMARY KEY, blob TEXT NOT NULL, updated INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS chunks (
  fid TEXT NOT NULL, n INTEGER NOT NULL, data BLOB NOT NULL, PRIMARY KEY (fid, n)
);
CREATE TABLE IF NOT EXISTS ratelimit (
  k TEXT PRIMARY KEY, count INTEGER NOT NULL, window_start INTEGER NOT NULL
);
